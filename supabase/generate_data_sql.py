import openpyxl, re, os

QR_FILE  = os.path.expanduser("~/Downloads/UCAT_QR_Complete_Question_Bank_Corrected.xlsx")
SJT_FILE = os.path.expanduser("~/Downloads/UCAT_SJT_Complete_Question_Bank_Expanded.xlsx")
OUT_FILE = os.path.join(os.path.dirname(__file__), "qr_sjt_data.sql")

def esc(v):
    if v is None:
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"

def letter_to_idx(letter):
    """'A' → 0, 'B' → 1, etc."""
    m = re.search(r'\b([A-E])\b', str(letter).upper())
    return ord(m.group(1)) - ord('A') if m else 0

lines = []
lines.append("-- Auto-generated by generate_data_sql.py — do not edit by hand")
lines.append("-- Run AFTER qr_sjt_migration.sql\n")

# ═══════════════════════════════════════════════════════════════════
# QR
# ═══════════════════════════════════════════════════════════════════
print("Reading QR data …")
wb = openpyxl.load_workbook(QR_FILE, read_only=True)

lines.append("-- ─── QR datasets ───────────────────────────────────────────────────────────")

seen_datasets = {}  # dataset_id → True

def process_qr_sheet(ws, sheet_name):
    rows = list(ws.iter_rows(values_only=True))
    # header row is always row index 3
    data = [r for r in rows[4:] if r[0] and isinstance(r[0], str) and '-Q' in str(r[0])]
    for r in data:
        q_id      = r[0]
        level     = r[1]   # Bronze / Silver / Gold
        topic     = r[2] or ''
        ds_id     = r[3]
        ds_title  = r[4] or ''
        fig_brief = r[5] or ''
        scenario  = r[6] or ''
        question  = r[7] or ''
        opt_a     = r[8] or ''
        opt_b     = r[9] or ''
        opt_c     = r[10] or ''
        opt_d     = r[11] or ''
        opt_e     = r[12] or ''
        correct   = r[13] or ''
        walkthru  = r[14] or ''
        skill     = r[15] or ''
        time_sec  = int(r[16]) if r[16] and str(r[16]).isdigit() else 45

        if ds_id not in seen_datasets:
            seen_datasets[ds_id] = True
            lines.append(
                f"INSERT INTO qr_datasets (id, title, figure_brief, scenario) VALUES "
                f"({esc(ds_id)}, {esc(ds_title)}, {esc(fig_brief)}, {esc(scenario)}) "
                f"ON CONFLICT (id) DO NOTHING;"
            )

        lines.append(
            f"INSERT INTO qr_questions "
            f"(id, dataset_id, difficulty, topic, question, option_a, option_b, option_c, option_d, option_e, "
            f"correct_answer, walkthrough, skill_tested, time_sec) VALUES "
            f"({esc(q_id)}, {esc(ds_id)}, {esc(level)}, {esc(topic)}, {esc(question)}, "
            f"{esc(opt_a)}, {esc(opt_b)}, {esc(opt_c)}, {esc(opt_d)}, {esc(opt_e)}, "
            f"{esc(correct)}, {esc(walkthru)}, {esc(skill)}, {time_sec}) "
            f"ON CONFLICT (id) DO NOTHING;"
        )

for sheet in ['QR Master', 'Silver', 'Gold']:
    process_qr_sheet(wb[sheet], sheet)
    print(f"  {sheet}: done")

lines.append(f"\n-- QR totals: {len(seen_datasets)} datasets, {sum(1 for l in lines if 'qr_questions' in l and 'INSERT' in l)} questions\n")

# ═══════════════════════════════════════════════════════════════════
