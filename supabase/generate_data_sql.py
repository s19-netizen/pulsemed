lines.append("-- ─── SJT questions ──────────────────────────────────────────────────────────")

AR_OPTIONS = [
    "A very appropriate thing to do",
    "Appropriate, but not ideal",
    "Inappropriate, but not awful",
    "A very inappropriate thing to do",
]
IR_OPTIONS = [
    "Very important",
    "Important",
    "Of minor importance",
    "Not important at all",
]

def normalise_ar(raw):
    raw = str(raw).strip().rstrip('.')
    for opt in AR_OPTIONS:
        if opt.lower() in raw.lower():
            return opt
    return raw

def normalise_ir(raw):
    raw = str(raw).strip().rstrip('.')
    for opt in IR_OPTIONS:
        if opt.lower() in raw.lower():
            return opt
    return raw

def parse_ml_options(raw):
    """Return (a_text, b_text, c_text) from newline-separated 'A. ...\nB. ...\nC. ...'"""
    parts = {'A': '', 'B': '', 'C': ''}
    for line in str(raw).split('\n'):
        m = re.match(r'^([A-C])\.\s*(.*)', line.strip())
        if m:
            parts[m.group(1)] = m.group(2).strip()
    return parts['A'], parts['B'], parts['C']

def parse_ml_correct(raw):
    """'Most appropriate: A. Least appropriate: C.' → mostCor=0, leastCor=2"""
    raw = str(raw)
    most = re.search(r'Most[^:]*:\s*([A-C])', raw, re.I)
    least = re.search(r'Least[^:]*:\s*([A-C])', raw, re.I)
    mc = ord(most.group(1).upper()) - ord('A') if most else 0
    lc = ord(least.group(1).upper()) - ord('A') if least else 2
    return mc, lc

seen_sjt = set()
sjt_count = 0

def process_sjt_sheet(ws, fmt):
    global sjt_count
    rows = list(ws.iter_rows(values_only=True))
    data = [r for r in rows if r[0] and isinstance(r[0], str) and re.match(r'^SJT\d+', r[0])]
    for r in data:
        q_id      = r[0]
        if q_id in seen_sjt:
            continue
        seen_sjt.add(q_id)

        scen_num   = r[1]
        scen_title = r[2] or ''
        scenario   = r[3] or ''
        theme      = r[4] or ''
        focus      = r[5] or ''
        difficulty = r[6] or 'Gold'
        question   = r[8] or ''
        raw_opts   = r[9] or ''
        raw_ans    = r[10] or ''
        walkthru   = r[11] or ''

        if fmt == 'appropriateness':
            correct = normalise_ar(raw_ans)
            a, b, c = '', '', ''
        elif fmt == 'importance':
            correct = normalise_ir(raw_ans)
            a, b, c = '', '', ''
        else:  # most-least
            a, b, c = parse_ml_options(raw_opts)
            mc, lc = parse_ml_correct(raw_ans)
            # encode as "mostCor:X|leastCor:Y" for easy parsing
            correct = f"most:{mc}|least:{lc}"

        scen_num_sql = str(scen_num) if scen_num else 'NULL'

        lines.append(
            f"INSERT INTO sjt_questions "
            f"(id, format, scenario_num, scenario_title, scenario, professional_theme, theme_focus, "
            f"difficulty, question, option_a, option_b, option_c, correct_answer, walkthrough) VALUES "
            f"({esc(q_id)}, {esc(fmt)}, {scen_num_sql}, {esc(scen_title)}, {esc(scenario)}, "
            f"{esc(theme)}, {esc(focus)}, {esc(difficulty)}, {esc(question)}, "
            f"{esc(a)}, {esc(b)}, {esc(c)}, {esc(correct)}, {esc(walkthru)}) "
            f"ON CONFLICT (id) DO NOTHING;"
        )
        sjt_count += 1

process_sjt_sheet(wb2['Appropriateness'], 'appropriateness')
print(f"  Appropriateness: done")
process_sjt_sheet(wb2['Importance'], 'importance')
print(f"  Importance: done")
process_sjt_sheet(wb2['Most & Least'], 'most-least')
print(f"  Most & Least: done")

lines.append(f"\n-- SJT total: {sjt_count} questions")

